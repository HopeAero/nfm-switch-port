static uint32_t mask_of(const bool *f, int32_t n) {
  uint32_t v = 0;
  for (int32_t a = 0; a < n; a++)
    if (f[a]) v |= 1u << a;
  return v;
}

int main(void) {
  int fails = 0;
  const int n = (int)(sizeof CASES / sizeof CASES[0]);
  for (int ci = 0; ci < n; ci++) {
    const Case *c = &CASES[ci];
    CareerSave s;
    memset(&s, 0, sizeof s);
    s.unlocked = c->unlocked;
    CareerRace r;
    memset(&r, 0, sizeof r);
    r.stage = c->stage;
    r.bonus = c->bonus;
    r.hardstage = c->hard != 0;
    r.nolevels = c->nolevels != 0;
    r.averagelevel = c->avg;
    r.sc[0] = c->car;
    set_seed(c->seed);
    m_reset();
    career_randomno(&r, &s);
    career_sortcars(&r, &s);
    uint32_t next = (uint32_t)(xs_random() * 4294967296.0);
    int32_t ms[6] = {m_cntrn, m_trn, m_rand[0], m_rand[1], m_rand[2],
                     (m_diup[0] ? 1 : 0) | (m_diup[1] ? 2 : 0) | (m_diup[2] ? 4 : 0)};
    bool ok = r.nplayers == c->np && r.noshadows == c->nosh;
    if (ok) {
      for (int32_t a = 0; a < c->np; a++) ok = ok && r.sc[a] == c->sc[a];
      ok = ok && mask_of(r.beast, c->np) == c->beast && mask_of(r.shadow, c->np) == c->shadow &&
           mask_of(r.undead, c->np) == c->undead && next == c->next && memcmp(ms, c->mstate, sizeof ms) == 0;
    }
    if (!ok) {
      fails++;
      printf("case %d (stage %d bonus %d hard %d unlocked %d car %d seed %08x): np %d/%d nosh %d/%d\n  sc  ", ci,
             c->stage, c->bonus, c->hard, c->unlocked, c->car, c->seed, r.nplayers, c->np, r.noshadows, c->nosh);
      for (int32_t a = 0; a < r.nplayers; a++) printf("%d,", r.sc[a]);
      printf("\n  exp ");
      for (int32_t a = 0; a < c->np; a++) printf("%d,", c->sc[a]);
      printf("\n  beast %x/%x shadow %x/%x undead %x/%x next %08x/%08x\n", mask_of(r.beast, r.nplayers), c->beast,
             mask_of(r.shadow, r.nplayers), c->shadow, mask_of(r.undead, r.nplayers), c->undead, next, c->next);
      if (fails > 10) break;
    }
  }
  if (fails) {
    printf("%d of %d cases FAILED\n", fails, n);
    return 1;
  }
  printf("%d cases, all tests passed\n", n);
  return 0;
}
