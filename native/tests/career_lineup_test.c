// java.js random(): xorshift32 on the sim stream.
static uint32_t g_seed;
static void set_seed(uint32_t s) { g_seed = s ? s : 1; }
static double xs_random(void) {
  uint32_t x = g_seed;
  x ^= x << 13;
  x ^= x >> 17;
  x ^= x << 5;
  g_seed = x;
  return x / 4294967296.0;
}

// Medium.random() (web/ext/Medium.js:331, sim bank): tenths that drift, fed by random().
static int32_t m_cntrn, m_trn, m_rand[3];
static bool m_diup[3];
static void m_reset(void) {
  m_cntrn = 0;
  m_trn = 0;
  memset(m_rand, 0, sizeof m_rand);
  memset(m_diup, 0, sizeof m_diup);
}
static double m_random(void) {
  if (m_cntrn == 0) {
    int i = 0;
    do {
      m_rand[i] = (int32_t)(10.0 * xs_random());
      double a = xs_random();
      double b = xs_random();
      m_diup[i] = !(a > b);
    } while (++i < 3);
    m_cntrn = 20;
  } else {
    m_cntrn--;
  }
  int j = 0;
  do {
    if (m_diup[j]) {
      if (++m_rand[j] == 10) m_rand[j] = 0;
    } else {
      if (--m_rand[j] == -1) m_rand[j] = 9;
    }
  } while (++j < 3);
  int32_t trn = m_trn + 1;
  if (trn == 3) trn = 0;
  m_trn = trn;
  return (double)((float)m_rand[trn] / 10.0f);
}

